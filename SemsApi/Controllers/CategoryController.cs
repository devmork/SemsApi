using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using Microsoft.EntityFrameworkCore;
using SemsApi.Data;
using SemsApi.DTO;
using SemsApi.Models.Eval;
using SemsApi.Utilities;

namespace SemsApi.Controllers
{
    /// <summary>
    /// Dedicated controller for TeacherEvaluationCategory CRUD operations.
    /// All category management lives here; the original EvaluationController is left unchanged.
    /// A category belongs to one EvaluationType, and its CatNo is unique across all evaluation types.
    /// </summary>
    [ApiController]
    [Route("api/evaluation/categories")]
    public class CategoryController : ControllerBase
    {
        private readonly ApplicationDbContext _context;

        public CategoryController(ApplicationDbContext context)
        {
            _context = context;
        }

        // ---------------------------------------------------------------------
        // READ
        // ---------------------------------------------------------------------

        /// <summary>
        /// List all categories. Optionally filter by evaluationTypeId.
        /// Ordered by CatNo.
        /// </summary>
        [HttpGet]
        public async Task<ActionResult<List<CategoryResponseDto>>> GetAll(
            [FromQuery] int? evaluationTypeId = null)
        {
            var query = _context.TeacherEvaluationCategories.AsNoTracking().AsQueryable();

            if (evaluationTypeId.HasValue)
                query = query.Where(c => c.EvaluationTypeId == evaluationTypeId.Value);

            var data = await query
                .OrderBy(c => c.CatNo)
                .Select(c => new CategoryResponseDto
                {
                    CatNo = c.CatNo,
                    EvaluationTypeId = c.EvaluationTypeId,
                    CatRn = c.CatRn,
                    CatName = c.CatName,
                    CatRate = c.CatRate
                })
                .ToListAsync();

            return Ok(data);
        }

        /// <summary>
        /// Get a single category by CatNo.
        /// </summary>
        [HttpGet("{catNo:int}")]
        public async Task<ActionResult<CategoryResponseDto>> GetById(int catNo)
        {
            var category = await _context.TeacherEvaluationCategories
                .AsNoTracking()
                .FirstOrDefaultAsync(c => c.CatNo == catNo);

            if (category is null)
                return NotFound(new { message = "Category not found." });

            return Ok(CategoryHelper.MapToResponse(category));
        }

        // ---------------------------------------------------------------------
        // CREATE
        // ---------------------------------------------------------------------

        /// <summary>
        /// Create a new evaluation category under an evaluation type.
        /// QA only. CatNo is generated by the database.
        /// </summary>
        //[Authorize(Roles = "QA")]
        [HttpPost]
        public async Task<ActionResult> Create([FromBody] CategoryRequestDto request)
        {
            var validationError = CategoryHelper.Validate(request);
            if (validationError is not null)
                return BadRequest(new { message = validationError });

            var typeExists = await _context.EvaluationTypes
                .AnyAsync(t => t.EvaluationTypeId == request.EvaluationTypeId);

            if (!typeExists)
                return BadRequest(new { message = "Evaluation type not found." });

            var entity = new TeacherEvaluationCategory
            {
                EvaluationTypeId = request.EvaluationTypeId!.Value,
                CatRn = request.CatRn!.Trim(),
                CatName = request.CatName!.Trim(),
                CatRate = Math.Round(request.CatRate!.Value, 2)
            };

            _context.TeacherEvaluationCategories.Add(entity);
            await _context.SaveChangesAsync();

            var response = CategoryHelper.MapToResponse(entity);

            return CreatedAtAction(
                nameof(GetById),
                new { catNo = entity.CatNo },
                new { message = "Category created successfully.", data = response });
        }

        // ---------------------------------------------------------------------
        // UPDATE
        // ---------------------------------------------------------------------

        /// <summary>
        /// Update an existing evaluation category.
        /// QA only. CatNo itself is never modified.
        /// </summary>
        //[Authorize(Roles = "QA")]
        [HttpPut("{catNo:int}")]
        public async Task<ActionResult> Update(int catNo, [FromBody] CategoryRequestDto request)
        {
            var category = await _context.TeacherEvaluationCategories
                .FirstOrDefaultAsync(c => c.CatNo == catNo);

            if (category is null)
                return NotFound(new { message = "Category not found." });

            var validationError = CategoryHelper.Validate(request);
            if (validationError is not null)
                return BadRequest(new { message = validationError });

            var typeExists = await _context.EvaluationTypes
                .AnyAsync(t => t.EvaluationTypeId == request.EvaluationTypeId);

            if (!typeExists)
                return BadRequest(new { message = "Evaluation type not found." });

            category.EvaluationTypeId = request.EvaluationTypeId!.Value;
            category.CatRn = request.CatRn!.Trim();
            category.CatName = request.CatName!.Trim();
            category.CatRate = Math.Round(request.CatRate!.Value, 2);

            await _context.SaveChangesAsync();

            return Ok(new
            {
                message = "Category updated successfully.",
                data = CategoryHelper.MapToResponse(category)
            });
        }

        // ---------------------------------------------------------------------
        // DELETE
        // ---------------------------------------------------------------------

        /// <summary>
        /// Delete an evaluation category.
        /// QA only.
        /// Refuses deletion when questions still belong to the category.
        /// </summary>
        //[Authorize(Roles = "QA")]
        [HttpDelete("{catNo:int}")]
        public async Task<ActionResult> Delete(int catNo)
        {
            var category = await _context.TeacherEvaluationCategories
                .FirstOrDefaultAsync(c => c.CatNo == catNo);

            if (category is null)
                return NotFound(new { message = "Category not found." });

            var hasDependentQuestions = await _context.TeacherEvaluationResults
                .AnyAsync(q => q.CatNo == catNo);

            if (hasDependentQuestions)
            {
                return Conflict(new
                {
                    message = "Cannot delete this category because evaluation questions are associated with it."
                });
            }

            _context.TeacherEvaluationCategories.Remove(category);
            await _context.SaveChangesAsync();

            return NoContent();
        }
    }
}