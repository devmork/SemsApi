using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using Microsoft.EntityFrameworkCore;
using SemsApi.Data;
using SemsApi.DTO;
using SemsApi.Models.Eval;

namespace SemsApi.Controllers
{
    /// <summary>
    /// CRUD for evaluation types (e.g. "Canteen Evaluation", "Teacher Evaluation - Grade 4 to 6").
    /// Any authenticated user can read; only Quality Assurance (QA) can create, update or delete.
    /// </summary>
    [ApiController]
    [Authorize]
    [Route("api/evaluation/types")]
    public class EvaluationTypeController : ControllerBase
    {
        private const int MaxNameLength = 50;

        private readonly ApplicationDbContext _context;

        public EvaluationTypeController(ApplicationDbContext context)
        {
            _context = context;
        }

        // ---------------------------------------------------------------------
        // READ
        // ---------------------------------------------------------------------

        /// <summary>
        /// List all evaluation types, ordered by id.
        /// </summary>
        [HttpGet]
        public async Task<ActionResult<List<EvaluationTypeResponseDto>>> GetAll()
        {
            var data = await _context.EvaluationTypes
                .AsNoTracking()
                .OrderBy(t => t.EvaluationTypeId)
                .Select(t => new EvaluationTypeResponseDto
                {
                    EvaluationTypeId = t.EvaluationTypeId,
                    EvaluationTypeName = t.EvaluationTypeName
                })
                .ToListAsync();

            return Ok(data);
        }

        /// <summary>
        /// Get a single evaluation type by id.
        /// </summary>
        [HttpGet("{evaluationTypeId:int}")]
        public async Task<ActionResult<EvaluationTypeResponseDto>> GetById(int evaluationTypeId)
        {
            var type = await _context.EvaluationTypes
                .AsNoTracking()
                .FirstOrDefaultAsync(t => t.EvaluationTypeId == evaluationTypeId);

            if (type is null)
                return NotFound(new { message = "Evaluation type not found." });

            return Ok(MapToDto(type));
        }

        // ---------------------------------------------------------------------
        // CREATE
        // ---------------------------------------------------------------------

        /// <summary>
        /// Create a new evaluation type. The id is generated by the database.
        /// </summary>
        [Authorize(Roles = "QA")]
        [HttpPost]
        public async Task<ActionResult> Create([FromBody] EvaluationTypeRequestDto request)
        {
            var validationError = Validate(request);
            if (validationError is not null)
                return BadRequest(new { message = validationError });

            var name = request.EvaluationTypeName!.Trim();

            if (await _context.EvaluationTypes.AnyAsync(t => t.EvaluationTypeName == name))
                return Conflict(new { message = "An evaluation type with this name already exists." });

            var entity = new EvaluationType { EvaluationTypeName = name };

            _context.EvaluationTypes.Add(entity);
            await _context.SaveChangesAsync();

            return CreatedAtAction(
                nameof(GetById),
                new { evaluationTypeId = entity.EvaluationTypeId },
                new { message = "Evaluation type created successfully.", data = MapToDto(entity) });
        }

        // ---------------------------------------------------------------------
        // UPDATE
        // ---------------------------------------------------------------------

        /// <summary>
        /// Rename an evaluation type. The id never changes.
        /// </summary>
        [Authorize(Roles = "QA")]
        [HttpPut("{evaluationTypeId:int}")]
        public async Task<ActionResult> Update(int evaluationTypeId, [FromBody] EvaluationTypeRequestDto request)
        {
            var type = await _context.EvaluationTypes
                .FirstOrDefaultAsync(t => t.EvaluationTypeId == evaluationTypeId);

            if (type is null)
                return NotFound(new { message = "Evaluation type not found." });

            var validationError = Validate(request);
            if (validationError is not null)
                return BadRequest(new { message = validationError });

            var name = request.EvaluationTypeName!.Trim();

            if (await _context.EvaluationTypes.AnyAsync(t =>
                    t.EvaluationTypeId != evaluationTypeId && t.EvaluationTypeName == name))
                return Conflict(new { message = "An evaluation type with this name already exists." });

            type.EvaluationTypeName = name;
            await _context.SaveChangesAsync();

            return Ok(new
            {
                message = "Evaluation type updated successfully.",
                data = MapToDto(type)
            });
        }

        // ---------------------------------------------------------------------
        // DELETE
        // ---------------------------------------------------------------------

        /// <summary>
        /// Delete an evaluation type. Refused while categories, forms or teacher comments still use it.
        /// </summary>
        [Authorize(Roles = "QA")]
        [HttpDelete("{evaluationTypeId:int}")]
        public async Task<ActionResult> Delete(int evaluationTypeId)
        {
            var type = await _context.EvaluationTypes
                .FirstOrDefaultAsync(t => t.EvaluationTypeId == evaluationTypeId);

            if (type is null)
                return NotFound(new { message = "Evaluation type not found." });

            var inUse =
                await _context.TeacherEvaluationCategories.AnyAsync(c => c.EvaluationTypeId == evaluationTypeId)
                || await _context.Forms.AnyAsync(f => f.EvaluationTypeId == evaluationTypeId)
                || await _context.TeacherEvaluationStrengths.AnyAsync(s => s.EvaluationTypeId == evaluationTypeId);

            if (inUse)
            {
                return Conflict(new
                {
                    message = "Cannot delete this evaluation type because categories, forms or comments are using it."
                });
            }

            _context.EvaluationTypes.Remove(type);
            await _context.SaveChangesAsync();

            return NoContent();
        }

        // ---------------------------------------------------------------------
        // HELPERS
        // ---------------------------------------------------------------------

        private static EvaluationTypeResponseDto MapToDto(EvaluationType t) =>
            new()
            {
                EvaluationTypeId = t.EvaluationTypeId,
                EvaluationTypeName = t.EvaluationTypeName
            };

        /// <summary>
        /// Returns an error message, or null when the request is valid.
        /// </summary>
        private static string? Validate(EvaluationTypeRequestDto request)
        {
            if (request is null)
                return "Request body is required.";

            if (string.IsNullOrWhiteSpace(request.EvaluationTypeName))
                return "EvaluationTypeName is required.";

            if (request.EvaluationTypeName.Trim().Length > MaxNameLength)
                return $"EvaluationTypeName must not exceed {MaxNameLength} characters.";

            return null;
        }
    }
}